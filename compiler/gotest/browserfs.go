package gotest

// Package tests run in a browser read and write files of the host, such as
// the testdata of the package, as they do when run in Bun. The browser has
// no filesystem of its own, so the runner installs a callback filesystem on
// the fs global (the filesystem that os uses in a browser, as in Go's
// js/wasm port) that calls a Vitest browser command, which performs each
// operation with the Node.js filesystem of the host. Relative paths are
// resolved against the directory of the package, which is the working
// directory of a Go test.

// browserHostFSServerFile is the Vitest config module that defines the
// browser command performing the host filesystem operations.
const browserHostFSServerFile = "goscript-browser-hostfs.mts"

// browserHostFSClientFile is the module that the browser runner imports
// first, which installs the callback filesystem on the fs global.
const browserHostFSClientFile = "goscript-browser-hostfs-client.ts"

// browserHostFSCommand is the name of the Vitest browser command.
const browserHostFSCommand = "goscriptHostFS"

const browserHostFSServer = `// Generated by goscript test: the host side of the browser filesystem.
import * as fs from "node:fs"

type encoded = { __goscriptBytes: string }

function decodeArg(arg: unknown): unknown {
  if (arg !== null && typeof arg === "object" && "__goscriptBytes" in arg) {
    return Buffer.from((arg as encoded).__goscriptBytes, "base64")
  }
  return arg
}

function encodeStat(stat: fs.Stats): Record<string, unknown> {
  return {
    __goscriptStat: true,
    isDir: stat.isDirectory(),
    isSymlink: stat.isSymbolicLink(),
    dev: stat.dev,
    ino: stat.ino,
    mode: stat.mode,
    nlink: stat.nlink,
    uid: stat.uid,
    gid: stat.gid,
    rdev: stat.rdev,
    size: stat.size,
    blksize: stat.blksize,
    blocks: stat.blocks,
    atimeMs: stat.atimeMs,
    mtimeMs: stat.mtimeMs,
    ctimeMs: stat.ctimeMs,
  }
}

function call(name: string, args: unknown[]): Promise<unknown[]> {
  const fn = (fs as unknown as Record<string, unknown>)[name]
  if (typeof fn !== "function") {
    const err = new Error("fs." + name + " is not implemented") as NodeJS.ErrnoException
    err.code = "ENOSYS"
    return Promise.reject(err)
  }
  return new Promise((resolve, reject) => {
    ;(fn as (...fnArgs: unknown[]) => void)(...args, (err: unknown, ...results: unknown[]) => {
      if (err) {
        reject(err)
        return
      }
      resolve(results)
    })
  })
}

// hostFS returns the browser command that performs filesystem operations
// for a package test running in the given directory.
export function hostFS(dir: string) {
  return async (_ctx: unknown, name: string, ...rawArgs: unknown[]) => {
    try {
      if (name === "init") {
        return { result: { cwd: dir, constants: fs.constants } }
      }
      const args = rawArgs.map(decodeArg)
      if (name === "read") {
        const [fd, length, position] = args as [number, number, number | null]
        const buf = Buffer.alloc(length)
        const [n] = (await call("read", [fd, buf, 0, length, position])) as [number]
        return { result: n, bytes: buf.subarray(0, n).toString("base64") }
      }
      const results = await call(name, args)
      const result = results[0]
      if (result instanceof fs.Stats) {
        return { result: encodeStat(result) }
      }
      return { result: result === undefined ? null : result }
    } catch (err) {
      const e = err as NodeJS.ErrnoException
      return { error: { message: String(e?.message ?? e), code: String(e?.code ?? "") } }
    }
  }
}
`

const browserHostFSClient = `// Generated by goscript test: the browser side of the host filesystem.
import { commands } from "vitest/browser"

type response = { result?: unknown; bytes?: string; error?: { message: string; code: string } }

const command = (commands as unknown as Record<string, (...args: unknown[]) => Promise<response>>)[` + "\"" + browserHostFSCommand + "\"" + `]

function toBase64(b: Uint8Array): string {
  let s = ""
  for (let i = 0; i < b.length; i += 0x8000) {
    s += String.fromCharCode(...b.subarray(i, i + 0x8000))
  }
  return btoa(s)
}

function fromBase64(s: string): Uint8Array {
  const bin = atob(s)
  const b = new Uint8Array(bin.length)
  for (let i = 0; i < bin.length; i++) {
    b[i] = bin.charCodeAt(i)
  }
  return b
}

function decodeResult(result: unknown): unknown {
  if (result !== null && typeof result === "object" && (result as { __goscriptStat?: boolean }).__goscriptStat) {
    const stat = result as Record<string, unknown>
    return {
      ...stat,
      isDirectory: () => stat.isDir === true,
      isFile: () => stat.isDir !== true && stat.isSymlink !== true,
      isSymbolicLink: () => stat.isSymlink === true,
      atime: new Date(stat.atimeMs as number),
      mtime: new Date(stat.mtimeMs as number),
      ctime: new Date(stat.ctimeMs as number),
    }
  }
  return result
}

function hostError(error: { message: string; code: string }): Error {
  const err = new Error(error.message) as Error & { code: string }
  err.code = error.code
  return err
}

// info is the working directory and open flag constants of the host, which
// hostFSReady requests from the host.
let info: { cwd: string; constants: Record<string, number> } | null = null
let ready: Promise<void> | null = null

// hostFSReady requests the host information once, and resolves when it has
// it. The runner awaits it before running the tests, rather than this module
// awaiting it while it loads, which can close the browser connection of a
// test whose page is still loading.
export function hostFSReady(): Promise<void> {
  ready ??= command("init").then((res) => {
    info = res.result as { cwd: string; constants: Record<string, number> }
    // A filesystem that a package installs on the fs global, such as one
    // over IndexedDB, keeps its own constants.
    for (const [name, value] of Object.entries(info.constants)) {
      if (!(name in constants)) {
        constants[name] = value
      }
    }
  })
  return ready
}

// handler returns the fs function that performs the named operation on the
// host. Byte arguments are sent as base64; read sends only the length and
// copies the bytes it receives into the buffer.
function handler(name: string) {
  return (...args: unknown[]) => {
    const callback = args.pop() as (err: unknown, ...results: unknown[]) => void
    let target: Uint8Array | null = null
    let targetOffset = 0
    let sent: unknown[]
    if (name === "read") {
      const [fd, buffer, offset, length, position] = args as [number, Uint8Array, number, number, number | null]
      target = buffer
      targetOffset = offset
      sent = [fd, length, position]
    } else if (name === "write") {
      const [fd, buffer, offset, length, position] = args as [number, Uint8Array, number, number, number | null]
      sent = [fd, { __goscriptBytes: toBase64(buffer.subarray(offset, offset + length)) }, 0, length, position]
    } else {
      sent = args.map((arg) => (arg instanceof Uint8Array ? { __goscriptBytes: toBase64(arg) } : arg))
    }
    hostFSReady().then(() => command(name, ...sent)).then(
      (res) => {
        if (res.error) {
          callback(hostError(res.error))
          return
        }
        if (target !== null && res.bytes !== undefined) {
          target.set(fromBase64(res.bytes), targetOffset)
        }
        callback(null, decodeResult(res.result))
      },
      (err) => callback(err),
    )
  }
}

const ops = [
  "chmod", "chown", "close", "fchmod", "fchown", "fstat", "fsync", "ftruncate",
  "lchown", "link", "lstat", "mkdir", "open", "read", "readdir", "readlink",
  "rename", "rmdir", "stat", "symlink", "truncate", "unlink", "utimes", "write",
]
const constants: Record<string, number> = {}
const hostFS: Record<string, unknown> = {
  constants,
  // cwd is the working directory that relative paths are resolved against.
  cwd: () => info?.cwd ?? "/",
}
for (const name of ops) {
  hostFS[name] = handler(name)
}
;(globalThis as { fs?: unknown }).fs = hostFS
`
