// bits4 returns the 4-bit value at i of a.
func bits4(a []uint8, i int) uint8 { return (a[i>>1] >> ((i & 1) << 2)) & 0b1111 }

// lookup reads two levels of nibbles, each through a constant slice.
func lookup(u int) uint8 {
	return bits4(nibbles[200:], int(bits4(nibbles[:], u&63))<<2+u&3)
}

// small is a table that is not deferred, read through each form of
// constant slice.
var small = [6]int{10, 20, 30, 40, 50, 60}

// sum adds the elements of a, which it only reads.
func sum(a []int) int {
	total := 0
	for _, v := range a {
		total += v
	}
	return total
}

// first passes a on to sum, so it only reads a too.
func first(a []int) int { return a[0] + sum(a[1:]) }

// word is a table of bytes converted to strings.
var word = []byte("goscript tables")

// computed is initialized by a call, before derived, which reads it
// through a constant slice during package initialization.
var computed = makeTable()

var derived = sum(computed[1:3])

func makeTable() []int {
	t := make([]int, 4)
	for i := range t {
		t[i] = i * 100
	}
	return t
}

// replaced is reassigned, so its slices are taken again each time.
var replaced = []int{1, 2, 3}

func replace() { replaced = []int{7, 8, 9} }

// written has its elements changed through a slice, so its slices are
// taken again each time.
var written = [4]int{1, 2, 3, 4}

func clobber(a []int) { a[0] = 99 }

// short is a slice whose constant slice bounds are out of range, which
// panics only when the slice is taken.
var short = []int{1, 2, 3}

func shortLen() int { return len(short[1:5]) }

func neverCalled() int { return len(short[:9]) }

// tryShortLen reports the panic of shortLen.
func tryShortLen() {
	defer func() {
		_, isError := recover().(error)
		println("recovered:", isError)
	}()
	println("short len:", shortLen())
}

func main() {
	// The two-level lookup gives the same values on every call.
	total := 0
	for u := 0; u < 512; u++ {
		total += int(lookup(u))
	}
	println("lookup total:", total, lookup(5), lookup(5))

	// The [lo:hi], [:hi], [lo:] and [:] forms of a table that is not
	// deferred.
	println("small:", sum(small[1:4]), sum(small[:2]), sum(small[3:]), sum(small[:]))
	println("small len/cap:", len(small[2:4]), cap(small[2:4]), len(small[:3:4]), cap(small[:3:4]))
	println("small first:", first(small[2:]), small[1:5][2])
	println("word:", string(word[:8]), string(word[9:]))

	// A table read during initialization.
	println("derived:", derived, sum(computed[1:3]), computed[1:][2])

	// A reassigned table gives the new elements.
	println("replaced before:", sum(replaced[1:]))
	replace()
	println("replaced after:", sum(replaced[1:]))

	// A table changed through a slice gives the changed elements.
	println("written before:", sum(written[1:]))
	clobber(written[1:])
	println("written after:", sum(written[1:]), written[1])

	// Out of range bounds panic each time the slice is taken, not before.
	tryShortLen()
	tryShortLen()
	if total < 0 {
		println(neverCalled())
	}
}
