//go:build ignore

// Command gen computes test vectors with Go's math/big and writes them to
// gs/math/big/testdata/vectors.ts. The index.test.ts file replays each vector
// against the gs/math/big override, so the override is checked against Go
// rather than against itself. Regenerate after a Go bump, from the repository
// root, with:
//
//	go run gs/math/big/gen.go |
//		npx prettier --stdin-filepath gs/math/big/testdata/vectors.ts \
//		> gs/math/big/testdata/vectors.ts.new &&
//		mv gs/math/big/testdata/vectors.ts.new gs/math/big/testdata/vectors.ts
//
// A vector is the operation name, its string arguments, and the expected
// result, all strings. An operation that returns several values joins them
// with "|".
//
// Each type has a pool of edge cases that every unary operation takes whole,
// and a small pool, a subset that still spans each kind of edge, for the
// binary, ternary and formatting operations. Crossing the full pools would
// grow the file past a megabyte and churn every diff.
package main

import (
	"fmt"
	"math"
	"math/big"
	"os"
	"slices"
	"strconv"
	"strings"
)

var vectors [][]string

func emit(op string, fields ...string) {
	vectors = append(vectors, append([]string{op}, fields...))
}

func bigInt(s string) *big.Int {
	v, ok := new(big.Int).SetString(s, 10)
	if !ok {
		panic("bad integer " + s)
	}
	return v
}

func float64Bits(f float64) string {
	return fmt.Sprintf("%016x", math.Float64bits(f))
}

func float32Bits(f float32) string {
	return fmt.Sprintf("%08x", math.Float32bits(f))
}

func accName(a big.Accuracy) string {
	return a.String()
}

func main() {
	genInt()
	genFloat()
	genRat()

	var b strings.Builder
	b.WriteString("// Code generated by gen.go; DO NOT EDIT.\n\n")
	b.WriteString("export const vectors: string[][] = [\n")
	for _, v := range vectors {
		b.WriteString("  [")
		for i, f := range v {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.Quote(f))
		}
		b.WriteString("],\n")
	}
	b.WriteString("]\n")
	os.Stdout.WriteString(b.String())
}

