var floatSmall = []string{"0", "-1", "0.1", "-7.25", "123456789.123456789", "1e-300"}

// floatBinary is crossed with itself for the arithmetic operations. 1e-300
// and 2.5e300 are far enough apart to need an exponent alignment of 1000 bits.
var floatBinary = []string{"0", "0.1", "-7.25", "1e-300", "2.5e300"}

var precs = []uint{1, 24, 53, 100}

var modes = []big.RoundingMode{
	big.ToNearestEven, big.ToNearestAway, big.ToZero, big.AwayFromZero,
	big.ToNegativeInf, big.ToPositiveInf,
}

func parseFloat(s string, prec uint) *big.Float {
	f, _, err := big.ParseFloat(s, 0, prec, big.ToNearestEven)
	if err != nil {
		panic(err)
	}
	return f
}

// floatState summarizes a Float exactly: the mantissa and exponent, the value
// in shortest decimal form, and the accuracy.
func floatState(f *big.Float) string {
	decimal := "-"
	// The decimal form of a huge exponent takes minutes and gigabytes.
	if exp := f.MantExp(nil); exp > -100000 && exp < 100000 {
		decimal = f.Text('g', -1)
	}
	return f.Text('p', 0) + "|" + decimal + "|" + accName(f.Acc())
}

func genFloat() {
	for _, s := range floatSmall {
		x := parseFloat(s, 200)
		for _, f := range []byte{'e', 'E', 'f', 'g', 'G', 'b', 'p', 'x'} {
			for _, prec := range []int{-1, 0, 5, 60} {
				emit("float.text", s, string(f), strconv.Itoa(prec), x.Text(f, prec))
			}
		}
		for _, verb := range []string{
			"%v", "%g", "%.10g", "%10.3f|", "%-12.4e|", "%+.5g", "% .5g", "%010.3f", "%x",
			"%b", "%.0f", "%s", "%G", "%E", "%F", "%.3x", "%#v",
		} {
			emit("float.format", verb, s, fmt.Sprintf(verb, x))
		}
		for _, prec := range precs {
			for _, mode := range modes {
				r := new(big.Float).SetMode(mode).SetPrec(prec).Set(x)
				emit("float.round", s, strconv.Itoa(int(prec)), strconv.Itoa(int(mode)),
					r.Text('p', 0)+"|"+accName(r.Acc()))
				if x.Sign() >= 0 {
					q := new(big.Float).SetMode(mode).SetPrec(prec).Sqrt(x)
					emit("float.sqrt", s, strconv.Itoa(int(prec)), strconv.Itoa(int(mode)), q.Text('p', 0))
				}
			}
		}
	}
	for _, s := range floatPool {
		x := parseFloat(s, 200)
		f64, acc := x.Float64()
		emit("float.float64", s, float64Bits(f64)+"|"+accName(acc))
		f32, acc := x.Float32()
		emit("float.float32", s, float32Bits(f32)+"|"+accName(acc))
		i64, acc := x.Int64()
		emit("float.int64", s, strconv.FormatInt(i64, 10)+"|"+accName(acc))
		u64, acc := x.Uint64()
		emit("float.uint64", s, strconv.FormatUint(u64, 10)+"|"+accName(acc))
		i, acc := x.Int(nil)
		emit("float.int", s, i.String()+"|"+accName(acc))
		r, acc := x.Rat(nil)
		if r == nil {
			emit("float.rat", s, "<nil>|"+accName(acc))
		} else {
			emit("float.rat", s, r.String()+"|"+accName(acc))
		}
		emit("float.isint", s, strconv.FormatBool(x.IsInt()))
		emit("float.minprec", s, strconv.Itoa(int(x.MinPrec())))
		emit("float.sign", s, strconv.Itoa(x.Sign()))
		m := new(big.Float)
		exp := x.MantExp(m)
		emit("float.mantexp", s, strconv.Itoa(exp)+"|"+m.Text('p', 0))
		gob, _ := x.GobEncode()
		emit("float.gob", s, fmt.Sprintf("%x", gob))
	}

	ops := []floatOp{
		{"add", (*big.Float).Add},
		{"sub", (*big.Float).Sub},
		{"mul", (*big.Float).Mul},
		{"quo", (*big.Float).Quo},
	}
	for _, xs := range floatBinary {
		for _, ys := range floatBinary {
			x, y := parseFloat(xs, 200), parseFloat(ys, 200)
			emit("float.cmp", xs, ys, strconv.Itoa(x.Cmp(y)))
			for _, prec := range []uint{53, 100} {
				for _, mode := range []big.RoundingMode{big.ToNearestEven, big.ToZero} {
					for _, op := range ops {
						if op.name == "quo" && y.Sign() == 0 && x.Sign() == 0 {
							continue
						}
						z := op.fn(new(big.Float).SetPrec(prec).SetMode(mode), x, y)
						emit("float."+op.name, xs, ys, strconv.Itoa(int(prec)), strconv.Itoa(int(mode)), floatState(z))
					}
				}
			}
		}
	}
	// An unrounded operation chooses the precision from its operands.
	emit("float.addmax", "1", "1e-100", floatState(new(big.Float).Add(parseFloat("1", 53), parseFloat("1e-100", 200))))

	type parse struct {
		s    string
		base int
	}
	for _, c := range []parse{
		{"0", 0}, {"-0", 0}, {"1", 0}, {"1.5", 0}, {".5", 0}, {"5.", 0}, {"1e100", 0}, {"1E-100", 0},
		{"-3.14159265358979323846264338327950288419716939937510582097494459e-300", 0},
		{"0x1.8p3", 0}, {"0X1P-2", 0}, {"0b101.1p2", 0}, {"0o17.4", 0}, {"1_000.5", 0},
		{"Inf", 0}, {"+Inf", 0}, {"-Inf", 0}, {"inf", 0}, {"infinity", 0}, {"nan", 0},
		{"", 0}, {"-", 0}, {"1e", 0}, {"1e+", 0}, {"1.2.3", 0}, {"1 ", 0}, {" 1", 0},
		{"1e99999999999", 0}, {"1e-99999999999", 0}, {"0x1p-2147483649", 0},
		{"ff.8", 16}, {"101.1", 2}, {"1.5", 10}, {"1__0", 0}, {"0x", 0},
		{"1e500", 0}, {"123456789012345678901234567890e-20", 0},
		{"\u0130", 0}, {"1\u0131", 0},
	} {
		for _, prec := range []uint{0, 53, 200} {
			f, b, err := big.ParseFloat(c.s, c.base, prec, big.ToNearestEven)
			if err != nil {
				emit("float.parse", c.s, strconv.Itoa(c.base), strconv.Itoa(int(prec)), "err|"+err.Error())
				continue
			}
			emit("float.parse", c.s, strconv.Itoa(c.base), strconv.Itoa(int(prec)),
				strconv.Itoa(b)+"|"+floatState(f)+"|"+strconv.Itoa(int(f.Prec())))
		}
	}

	// Constants whose digits depend on correct rounding at every step.
	for _, prec := range []uint{64, 200, 1700} {
		for _, n := range []string{"2", "3", "5", "10", "0.5", "1e-20", "1e100", "1e200"} {
			z := new(big.Float).SetPrec(prec).Sqrt(parseFloat(n, 200))
			emit("float.sqrt", n, strconv.Itoa(int(prec)), "0", z.Text('p', 0))
		}
	}
	for _, s := range []string{
		"1e500", "1e-500", "3.14159e700", "123456789e-400", "2e1000", "7e-1000",
	} {
		z := parseFloat(s, 1700)
		emit("float.text1700", s, "g", "500", z.Text('g', 500))
		emit("float.text1700", s, "f", "30", z.Text('f', 30))
	}

	emit("float.setfloat64", float64Bits(math.Pi), floatState(new(big.Float).SetFloat64(math.Pi)))
	emit("float.setfloat64", float64Bits(5e-324), floatState(new(big.Float).SetFloat64(5e-324)))
	emit("float.setfloat64", float64Bits(math.MaxFloat64), floatState(new(big.Float).SetFloat64(math.MaxFloat64)))
	emit("float.setfloat64", float64Bits(-0.1), floatState(new(big.Float).SetFloat64(-0.1)))
	emit("float.setfloat64", float64Bits(math.Inf(-1)), floatState(new(big.Float).SetFloat64(math.Inf(-1))))
	for _, s := range intPool {
		x := bigInt(s)
		emit("float.setint", s, floatState(new(big.Float).SetInt(x)))
		emit("float.setint30", s, floatState(new(big.Float).SetPrec(30).SetInt(x)))
	}
}

