func genInt() {
	binary := []intOp{
		{"add", (*big.Int).Add},
		{"sub", (*big.Int).Sub},
		{"mul", (*big.Int).Mul},
		{"and", (*big.Int).And},
		{"or", (*big.Int).Or},
		{"xor", (*big.Int).Xor},
		{"andnot", (*big.Int).AndNot},
	}
	divide := []intOp{
		{"quo", (*big.Int).Quo},
		{"rem", (*big.Int).Rem},
		{"div", (*big.Int).Div},
		{"mod", (*big.Int).Mod},
	}
	for _, xs := range intPool {
		x := bigInt(xs)
		emit("int.abs", xs, new(big.Int).Abs(x).String())
		emit("int.neg", xs, new(big.Int).Neg(x).String())
		emit("int.not", xs, new(big.Int).Not(x).String())
		emit("int.sign", xs, strconv.Itoa(x.Sign()))
		emit("int.bitlen", xs, strconv.Itoa(x.BitLen()))
		emit("int.tzb", xs, strconv.Itoa(int(x.TrailingZeroBits())))
		emit("int.int64", xs, strconv.FormatInt(x.Int64(), 10))
		emit("int.uint64", xs, strconv.FormatUint(x.Uint64(), 10))
		emit("int.isint64", xs, strconv.FormatBool(x.IsInt64()))
		emit("int.isuint64", xs, strconv.FormatBool(x.IsUint64()))
		f, acc := new(big.Int).Set(x).Float64()
		emit("int.float64", xs, float64Bits(f)+"|"+accName(acc))
		emit("int.bytes", xs, fmt.Sprintf("%x", x.Bytes()))
		emit("int.probablyprime", xs, strconv.FormatBool(x.ProbablyPrime(20)))
		if x.Sign() >= 0 {
			emit("int.sqrt", xs, new(big.Int).Sqrt(x).String())
		}
	}

	for _, xs := range intSmall {
		x := bigInt(xs)
		for _, base := range []int{2, 8, 10, 16, 36, 62} {
			emit("int.text", xs, strconv.Itoa(base), x.Text(base))
		}
		for _, n := range []int{0, 1, 64, 200} {
			emit("int.lsh", xs, strconv.Itoa(n), new(big.Int).Lsh(x, uint(n)).String())
			emit("int.rsh", xs, strconv.Itoa(n), new(big.Int).Rsh(x, uint(n)).String())
			emit("int.bit", xs, strconv.Itoa(n), strconv.Itoa(int(x.Bit(n))))
		}
		for _, n := range []int{0, 63, 65} {
			emit("int.setbit", xs, strconv.Itoa(n), "1", new(big.Int).SetBit(x, n, 1).String())
			emit("int.setbit", xs, strconv.Itoa(n), "0", new(big.Int).SetBit(x, n, 0).String())
		}
		for _, verb := range []string{
			"%d", "%+d", "% d", "%x", "%X", "%#x", "%#X", "%o", "%#o", "%O", "%b", "%#b",
			"%10d", "%-10d|", "%010d", "%.5d", "%+.3x", "%s", "%v", "%q", "%#v",
		} {
			emit("int.format", verb, xs, fmt.Sprintf(verb, x))
		}
		for _, ys := range intSmall {
			y := bigInt(ys)
			for _, op := range binary {
				emit("int."+op.name, xs, ys, op.fn(new(big.Int), x, y).String())
			}
			emit("int.cmp", xs, ys, strconv.Itoa(x.Cmp(y)))
			emit("int.cmpabs", xs, ys, strconv.Itoa(x.CmpAbs(y)))
			emit("int.gcd", xs, ys, new(big.Int).GCD(nil, nil, x, y).String())
			if y.Sign() != 0 {
				for _, op := range divide {
					emit("int."+op.name, xs, ys, op.fn(new(big.Int), x, y).String())
				}
				q, r := new(big.Int).QuoRem(x, y, new(big.Int))
				emit("int.quorem", xs, ys, q.String()+"|"+r.String())
				d, m := new(big.Int).DivMod(x, y, new(big.Int))
				emit("int.divmod", xs, ys, d.String()+"|"+m.String())
				if inv := new(big.Int).ModInverse(x, y); inv != nil {
					emit("int.modinverse", xs, ys, inv.String())
				} else {
					emit("int.modinverse", xs, ys, "nil")
				}
			}
			if y.Sign() > 0 && y.Bit(0) == 1 {
				emit("int.jacobi", xs, ys, strconv.Itoa(big.Jacobi(x, y)))
			}
		}
		for _, es := range []string{"0", "1", "5", "257", "-3"} {
			e := bigInt(es)
			// An unreduced power of a large base with a large exponent has
			// thousands of digits.
			if e.Cmp(big.NewInt(5)) <= 0 {
				emit("int.exp", xs, es, "0", new(big.Int).Exp(x, e, nil).String())
			}
			for _, ms := range []string{"1", "97", "18446744073709551557", "-97"} {
				m := bigInt(ms)
				emit("int.exp", xs, es, ms, new(big.Int).Exp(x, e, m).String())
			}
		}
	}
	for _, ps := range sqrtPrimes {
		p := bigInt(ps)
		for _, xs := range intSmall {
			x := bigInt(xs)
			// A square root is not unique: report the square it must have.
			if r := new(big.Int).ModSqrt(x, p); r != nil {
				sq := new(big.Int).Mod(new(big.Int).Mul(r, r), p)
				emit("int.modsqrt", xs, ps, sq.String())
			} else {
				emit("int.modsqrt", xs, ps, "nil")
			}
		}
	}
	for _, p := range primePool {
		emit("int.probablyprime", p, "true")
	}
	for _, c := range []string{
		"561", "1105", "3215031751", "3825123056546413051", "318665857834031151167461",
		"3317044064679887385961981", "18446744073709551617", "2047", "1373653",
	} {
		emit("int.probablyprime", c, strconv.FormatBool(bigInt(c).ProbablyPrime(20)))
	}
	for _, r := range [][2]int64{{1, 1}, {1, 20}, {5, 30}, {-3, 4}, {10, 5}, {0, 7}} {
		emit("int.mulrange", strconv.FormatInt(r[0], 10), strconv.FormatInt(r[1], 10),
			new(big.Int).MulRange(r[0], r[1]).String())
	}
	for _, r := range [][2]int64{{5, 2}, {10, 0}, {10, 10}, {52, 5}, {100, 50}, {3, 5}, {5, -1}, {0, -1}, {-3, -5}} {
		emit("int.binomial", strconv.FormatInt(r[0], 10), strconv.FormatInt(r[1], 10),
			new(big.Int).Binomial(r[0], r[1]).String())
	}

	type setString struct {
		s    string
		base int
	}
	for _, c := range []setString{
		{"0", 10}, {"-0", 10}, {"+12", 10}, {"-12345678901234567890123", 10}, {"ff", 16},
		{"FF", 16}, {"zZ", 62}, {"zZ", 36}, {"101", 2}, {"0x1f", 0}, {"0b101", 0}, {"0o17", 0},
		{"017", 0}, {"1_000", 0}, {"1__0", 0}, {"_1", 0}, {"", 10}, {"-", 10}, {"12a", 10},
		{"0x", 0}, {"9", 8}, {" 1", 10}, {"1 ", 10}, {"0X1F", 0}, {"-0x1F", 0},
		// U+0130 and U+0131 are not ASCII digits, though their low byte is.
		{"\u0130", 10}, {"\u0131", 10}, {"1\u0131", 10}, {"0x\u0131", 0},
	} {
		if v, ok := new(big.Int).SetString(c.s, c.base); ok {
			emit("int.setstring", c.s, strconv.Itoa(c.base), v.String())
		} else {
			emit("int.setstring", c.s, strconv.Itoa(c.base), "fail")
		}
	}
	for _, xs := range intPool {
		x := bigInt(xs)
		buf, _ := x.MarshalJSON()
		emit("int.json", xs, string(buf))
		gob, _ := x.GobEncode()
		emit("int.gob", xs, fmt.Sprintf("%x", gob))
	}
}

type intOp struct {
	name string
	fn   func(z, x, y *big.Int) *big.Int
}

type floatOp struct {
	name string
	fn   func(z, x, y *big.Float) *big.Float
}

type ratOp struct {
	name string
	fn   func(z, x, y *big.Rat) *big.Rat
}

