package goscript

import (
	"bytes"
	"flag"
	"io/fs"
	"os"
	"path"
	"strings"
	"testing"
)

// updateEmbed rewrites gs-embed.go from the gs/ tree.
var updateEmbed = flag.Bool("update", false, "rewrite gs-embed.go from the gs/ tree")

// TestGsOverrides checks that the embedded tree holds the builtin runtime.
func TestGsOverrides(t *testing.T) {
	data, err := fs.ReadFile(GsOverrides, "gs/builtin/builtin.ts")
	if err != nil {
		t.Fatal(err)
	}
	if len(data) == 0 {
		t.Fatal("gs/builtin/builtin.ts is empty")
	}
}

// TestGsEmbedCurrent checks that gs-embed.go names exactly the compiler inputs
// in the gs/ tree. Run go generate to rewrite it after adding or removing one.
func TestGsEmbedCurrent(t *testing.T) {
	// Render the embed file the gs/ tree calls for.
	want, err := renderGsEmbed(os.DirFS("."))
	if err != nil {
		t.Fatal(err)
	}

	// Rewrite the file on request, or compare it with the rendering.
	if *updateEmbed {
		if err := os.WriteFile("gs-embed.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("gs-embed.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatal("gs-embed.go is stale; run go generate")
	}
}

// TestGsOverridesExcludeTests checks that no test or fixture ships in the
// embedded gs/ tree.
func TestGsOverridesExcludeTests(t *testing.T) {
	err := fs.WalkDir(GsOverrides, "gs", func(filePath string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() && !isGsCompilerInput(filePath) {
			t.Errorf("embedded gs/ tree includes %s", filePath)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
}

// renderGsEmbed returns gs-embed.go with one embed directive per compiler
// input under gs/ in fsys.
func renderGsEmbed(fsys fs.FS) ([]byte, error) {
	// Collect the compiler inputs in walk order, which is lexical.
	var inputs []string
	err := fs.WalkDir(fsys, "gs", func(filePath string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !entry.IsDir() && isGsCompilerInput(filePath) {
			inputs = append(inputs, filePath)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}

	// Write the generated file around the directives.
	var out bytes.Buffer
	out.WriteString(`// Code generated by go test -run TestGsEmbedCurrent -update. DO NOT EDIT.

package goscript

import "embed"

// GsOverrides holds the hand-written TypeScript packages that implement Go
// packages, with the metadata and parity ledgers the compiler reads. An embed
// pattern cannot exclude files, so each input is named here and the package
// tests stay out of every binary that embeds the compiler.
//
`)
	for _, input := range inputs {
		out.WriteString("//go:embed " + input + "\n")
	}
	out.WriteString("var GsOverrides embed.FS\n")
	return out.Bytes(), nil
}

// isGsCompilerInput reports whether a gs/ file is read by the compiler: a
// TypeScript source other than a test, or a package's metadata or parity
// ledger. Tests, fixtures, notes, and generators stay out.
func isGsCompilerInput(filePath string) bool {
	if strings.Contains(filePath, "/testdata/") {
		return false
	}
	switch name := path.Base(filePath); {
	case name == "meta.json", name == "parity.json":
		return true
	case strings.HasSuffix(name, ".test.ts"):
		return false
	default:
		return strings.HasSuffix(name, ".ts")
	}
}

// TestRuntimeDependencies checks that package.json lists versioned runtime
// dependencies.
func TestRuntimeDependencies(t *testing.T) {
	deps, err := RuntimeDependencies()
	if err != nil {
		t.Fatal(err)
	}
	if len(deps) == 0 {
		t.Fatal("expected runtime npm dependencies")
	}
	for name, version := range deps {
		if version == "" {
			t.Fatalf("runtime npm dependency %s has no version", name)
		}
	}
}

// TestBrowserTestDependencies checks that package.json lists versioned
// browser test dependencies.
func TestBrowserTestDependencies(t *testing.T) {
	deps, err := BrowserTestDependencies()
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range browserTestPackages {
		if deps[name] == "" {
			t.Fatalf("browser test npm dependency %s has no version", name)
		}
	}
}
